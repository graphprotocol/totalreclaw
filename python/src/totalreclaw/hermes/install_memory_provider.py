"""Install TotalReclaw as a Hermes MemoryProvider (Path B — issue #275).

This module drops a one-file sidecar at
``$HERMES_HOME/plugins/totalreclaw/__init__.py`` so Hermes'
built-in memory-provider loader picks up :class:`TotalReclawMemoryProvider`
without needing an upstream API addition.

Why a sidecar
-------------
Hermes' plugin context (``ctx`` passed to ``register()``) does not
expose ``register_memory_provider`` — only tools and lifecycle hooks.
Memory providers are discovered by scanning ``$HERMES_HOME/plugins/<name>/``
(user-installed) for ``MemoryProvider`` subclasses — NOT the nested
``plugins/memory/<name>/`` layout, which is the *bundled* (in-tree)
location only. (Getting this path wrong was the 2026-06-10 split-brain
bug; see :func:`sidecar_path`.) The sidecar imports our class from
the installed ``totalreclaw`` PyPI package, so the heavy lifting stays
in the main distribution.

Resilient edition (issue #638, 2026-09-07)
------------------------------------------
The sidecar used to be a bare 3-line re-export stub. That had two
defects: it carried no ``register()`` (so when it replaced a git-plugin
bootstrap file, the *next* plugin reload silently dropped every
``totalreclaw_*`` tool + hook), and it had no bootstrap (so a Hermes
runtime regeneration that recreated the venv without the pip-installed
``totalreclaw`` package killed the import and the plugin vanished with
**no error anywhere** — Hermes does not surface an unmet ``requires:``).

``_SIDECAR_CONTENT`` is now a full, self-healing plugin file (the
rc.10 git-plugin bootstrap behaviour, ported): on ``ImportError`` it
makes one bounded attempt to reinstall the package into the RUNNING
interpreter's venv; if that fails it still loads in DEGRADED mode,
registering a ``totalreclaw_status`` tool that reports exactly what is
wrong and how to fix it. The state-dir writability probe from the git
bootstrap is deliberately NOT ported — it does not impede the two jobs
this file has (provider re-export + register delegation) and raising at
import time would take down provider discovery with it.

UX
--
Activation flow handled by the agent (see ``SKILL.md``):

  1. Read current provider via :func:`read_active_provider` (config grep —
     upstream ``hermes memory status --json`` is not yet released; see
     spec §"Open questions for upstream").
  2. If ``"none"`` / ``""`` / ``"totalreclaw"``: call
     :func:`install_and_activate` silently (pairing already does this, see
     :func:`activate_after_pairing`).
  3. If another provider is active: ask the user "switch or tools-only?".
     - **switch** → :func:`install_sidecar` + :func:`set_active_provider`
       (warn that the previous provider deactivates).
     - **tools-only** → :func:`install_sidecar` only; TR tools remain
       available, hooks don't fire because TR isn't the active provider.

Activation keeps Hermes' built-in memory (``USER.md`` / ``MEMORY.md``)
running beside TotalReclaw: Hermes always keeps its builtin provider next to
the one external provider, and the provider mirrors the built-in memory
tool's writes through ``on_memory_write``. ``exclusive=True`` (CLI
``--exclusive``) also turns the built-in stores off, the pre-2.5.3rc4
default.

All operations are idempotent: rerunning on an already-installed
sidecar overwrites with the current shim content (catches package
upgrades that change the import path) without disturbing other state.
That idempotent rewrite is also the healing path for boxes still
carrying the old bare stub: a single re-pair or one
``install-memory-provider --force`` replaces it with the resilient file.
"""
