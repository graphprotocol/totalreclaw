"""DEP-4 PII / credential filter — cross-language parity (Python / PyO3 side).

Loads ``tests/parity/pii/corpus.json`` (generated by
``tests/parity/pii/generate_corpus.py``) and asserts that
``totalreclaw_core.pii_filter`` returns exactly each item's expected decision
and category. The Rust runner (``rust/totalreclaw-core/tests/pii_corpus.rs``)
and the WASM runner (``tests/parity/pii/pii-parity.test.ts``) assert the same
expectations, so all three runtimes agree item-for-item.

CI builds ``totalreclaw_core`` from local source (``python-tests`` job), so a
missing binding there is a real failure. A developer venv holding an older
PyPI wheel skips instead; build the local crate first:
``cd rust/totalreclaw-core && maturin develop --release --features python-extension``.

Run with: ``cd python && python -m pytest tests/test_pii_parity.py -v``
"""
from __future__ import annotations

import json
import os
from pathlib import Path

import pytest

totalreclaw_core = pytest.importorskip("totalreclaw_core")

CORPUS_PATH = Path(__file__).resolve().parents[2] / "tests" / "parity" / "pii" / "corpus.json"

pytestmark = pytest.mark.skipif(
    not hasattr(totalreclaw_core, "pii_filter") and not os.environ.get("CI"),
    reason="installed totalreclaw_core predates pii_filter (DEP-4); build the local crate",
)


def _items() -> list[dict]:
    return json.loads(CORPUS_PATH.read_text(encoding="utf-8"))["items"]


@pytest.mark.parametrize("item", _items(), ids=lambda item: item["id"])
def test_pii_filter_matches_corpus(item: dict) -> None:
    out = json.loads(totalreclaw_core.pii_filter(item["text"]))
    assert (out["decision"], out.get("category")) == (item["expect"], item.get("category")), item["id"]
    if out["decision"] == "allow":
        assert set(out) == {"decision"}
    else:
        assert out["message"].startswith("Not saved: ")


def test_pii_filter_allow_wire_shape_is_byte_exact() -> None:
    assert totalreclaw_core.pii_filter("my doctor is Dr. X") == '{"decision":"allow"}'


def test_pii_filter_block_wire_shape_has_fixed_key_order() -> None:
    raw = totalreclaw_core.pii_filter("card 4111 1111 1111 1111")
    assert raw.startswith('{"decision":"block","category":"payment_card","message":"Not saved: ')


def test_corpus_meets_prd04_g4_sizes() -> None:
    items = _items()
    assert len(items) >= 150
    assert {i["set"] for i in items} == {"negative", "positive"}
